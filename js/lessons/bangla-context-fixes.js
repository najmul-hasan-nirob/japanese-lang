  function applyLesson(lesson, map) {
    if (!lesson || !map) return;
    const walk = value => {
      if (!value || typeof value !== 'object') return;
      if (Array.isArray(value)) return value.forEach(walk);
      if (typeof value.jp === 'string' && Object.prototype.hasOwnProperty.call(map, value.jp)) {
        value.bn = map[value.jp];
      }
      Object.keys(value).forEach(k => { if (k !== 'bn') walk(value[k]); });
    };
    walk(lesson);
  }

